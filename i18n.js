window.setPlatformLanguage = function(lang) {
  const dict = window.CC_TRANSLATIONS[lang] || window.CC_TRANSLATIONS['en'];
  
  if (dict.brand_sub && document.querySelector('.brand-sub')) {
    document.querySelector('.brand-sub').textContent = dict.brand_sub;
  }
  if (dict.track_btn && document.getElementById('btnOpenOrderTrolley')) {
    document.getElementById('btnOpenOrderTrolley').textContent = dict.track_btn;
  }
  if (dict.install_btn && document.getElementById('btnInstallApp')) {
    document.getElementById('btnInstallApp').textContent = dict.install_btn;
  }
  if (dict.gateway_btn && document.getElementById('openGatewayBtn')) {
    document.getElementById('openGatewayBtn').textContent = dict.gateway_btn;
  }
  if (dict.hero_badge && document.querySelector('.hero-badge-text')) {
    document.querySelector('.hero-badge-text').textContent = dict.hero_badge;
  }
  if (dict.hero_title && document.getElementById('heroTitle')) {
    document.getElementById('heroTitle').innerHTML = dict.hero_title;
  }
  if (dict.hero_desc && document.getElementById('heroDescription')) {
    document.getElementById('heroDescription').textContent = dict.hero_desc;
  }
  if (dict.book_priority && document.getElementById('whatsappBookingBtn')) {
    document.getElementById('whatsappBookingBtn').textContent = dict.book_priority;
  }

  // RTL handling for Arabic
  if (lang === 'ar') {
    document.body.style.direction = 'rtl';
  } else {
    document.body.style.direction = 'ltr';
  }

  console.log('[i18n] Language switched to:', lang);
};
